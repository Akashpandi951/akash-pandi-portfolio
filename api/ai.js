/**
 * api/ai.js
 * Google Gemini AI Integration for B. Akash Pandi's Portfolio.
 * Uses the Google Interactions API with the user's Gemini API key.
 */

const express = require('express');
const router = express.Router();
const { requireAdminAuth, contactLimiter } = require('./middleware');

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const INTERACTIONS_URL = 'https://generativelanguage.googleapis.com/v1beta/interactions';
const MODEL_NAME = 'gemini-3.5-flash';

/**
 * Helper to call Google Interactions API
 */
async function callGemini(inputPrompt, previousId = null) {
  if (!GEMINI_API_KEY || GEMINI_API_KEY.includes('placeholder')) {
    throw new Error('GEMINI_API_KEY is unconfigured in server environment.');
  }

  const payload = {
    model: MODEL_NAME,
    input: inputPrompt
  };

  if (previousId) {
    payload.previous_interaction_id = previousId;
  }

  const response = await fetch(INTERACTIONS_URL, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-goog-api-key': GEMINI_API_KEY
    },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errText = await response.text();
    console.error('[Gemini API HTTP Error]', response.status, errText);
    throw new Error(`Gemini API error (HTTP ${response.status}): ${errText}`);
  }

  const data = await response.json();
  const steps = data.steps || [];
  const modelStep = steps.find(s => s.type === 'model_output');
  const textOutput = modelStep ? modelStep.content?.find(c => c.type === 'text')?.text : '';

  return {
    id: data.id,
    text: textOutput || 'No output generated by Gemini.'
  };
}

/**
 * POST /api/ai/draft-reply
 * Protected admin endpoint: Generates an intelligent, tailored email response draft for an inquiry.
 */
router.post('/draft-reply', requireAdminAuth, async (req, res) => {
  try {
    const { name, email, message } = req.body;

    if (!message || !message.trim()) {
      return res.status(400).json({
        success: false,
        error: 'Inquiry message text is required to generate draft.'
      });
    }

    const prompt = `You are the executive AI assistant for B. Akash Pandi, an Aspiring Data Analyst & AI Tools Enthusiast based in India.
Akash received the following contact message:
- Sender Name: ${name || 'Prospective Partner'}
- Sender Email: ${email || 'Unknown'}
- Message:
"${message.trim()}"

Write a professional, warm, concise email reply draft responding directly to their points.
Tone guidelines:
1. Express genuine enthusiasm and gratitude for reaching out.
2. Address specific topics mentioned (data analytics, SQL, AI tools, employment, or collaboration).
3. Offer concrete next steps (e.g. scheduling a brief introductory call or sharing further project details).
4. Keep it between 2 to 3 concise paragraphs.
5. Sign off respectfully as:
Warm regards,
B. Akash Pandi
Aspiring Data Analyst & AI Tools Enthusiast
akashpandi506@gmail.com`;

    const result = await callGemini(prompt);

    return res.json({
      success: true,
      draft: result.text,
      model: MODEL_NAME
    });

  } catch (err) {
    console.error('[AI Draft Reply Error]', err);
    return res.status(500).json({
      success: false,
      error: 'Failed to generate AI reply draft: ' + (err.message || 'Unknown error')
    });
  }
});

/**
 * POST /api/ai/chat
 * Public endpoint: Visitors can ask questions about Akash's skills, projects, and background.
 */
router.post('/chat', contactLimiter, async (req, res) => {
  try {
    const { message, previousInteractionId } = req.body;

    if (!message || !message.trim()) {
      return res.status(400).json({
        success: false,
        error: 'Message cannot be empty.'
      });
    }

    const cleanInput = message.trim();
    if (cleanInput.length > 500) {
      return res.status(400).json({
        success: false,
        error: 'Question is too long (maximum 500 characters).'
      });
    }

    const systemContext = `You are "Akash AI" — the official interactive AI portfolio assistant for B. Akash Pandi.
About B. Akash Pandi:
- Title: Aspiring Data Analyst & AI Tools Enthusiast
- Contact Email: akashpandi506@gmail.com
- Core Expertise: Data Analytics, SQL Querying & Optimization, Python (Pandas/NumPy), Microsoft Excel, Power BI, AI Tools & Structured Prompt Engineering, Web Development.
- Portfolio Highlights:
  1. AI Tools – Website & Application Development: Created modern web applications using prompt engineering, Tailwind CSS, JavaScript, and AI tools.
  2. Data Analytics & SQL Projects: Data transformation, exploratory analysis, and business intelligence reporting.
- Aspirations: Seeking Junior Data Analyst or Associate Data Analyst opportunities, entry-level data roles, and collaborative technical projects.
- Website Features: Interactive portfolio, real-time Contact Form, and a secure Supabase/Express full-stack contact management system.

Answer visitor questions accurately, warmly, and concisely (2-4 sentences max). If they want to hire or reach Akash, encourage them to use the Contact section or email akashpandi506@gmail.com directly. Do not invent false credentials.

Visitor Question: "${cleanInput}"`;

    const result = await callGemini(systemContext, previousInteractionId || null);

    return res.json({
      success: true,
      reply: result.text,
      interactionId: result.id
    });

  } catch (err) {
    console.error('[AI Chat Error]', err);
    return res.status(500).json({
      success: false,
      error: 'AI assistant is currently resting. Please reach out to Akash directly via the contact form!'
    });
  }
});

module.exports = router;
